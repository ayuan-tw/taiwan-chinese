// Build-time only. Public bundled words are a one-time migration seed, never a
// second authority after bootstrap. No personal or remotely fetched data enters.
import { readFile, writeFile } from 'node:fs/promises';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const context = vm.createContext({ window: { dispatchEvent() {} }, CustomEvent: function () {} });
vm.runInContext(await readFile(new URL('data/words.js', root), 'utf8') + '\n' + await readFile(new URL('js/data-model.js', root), 'utf8'), context);
const seed = context.window.CHENGCI_DATA_MODEL.filterByType('word').map(item => ({
  id: item.id,
  data: Object.fromEntries([
    ...['word', 'zhuyin', 'meaning', 'example', 'exampleZhuyin', 'note', 'category', 'confuse'].map(key => [key, String(item[key] || '').trim()]),
    ['pronunciationStatus', item.zhuyin ? 'confirmed' : 'missing'],
    ['tags', [...item.tags]]
  ])
}));
if (!seed.length || seed.length !== new Set(seed.map(item => item.id)).size) throw new Error('Vocabulary seed IDs must be present and unique.');
const output = '// Generated by generate-vocabulary-seed.mjs from public word data.\n// Used only once, on the owner-approved unified vocabulary bootstrap.\nexport const vocabularySeed = ' + JSON.stringify(seed, null, 2) + ';\n';
const destination = new URL('./vocabulary-seed.mjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== output) throw new Error('Vocabulary seed differs from source. Review and regenerate it before publishing.');
} else await writeFile(destination, output);
console.log(`${seed.length} word IDs ${process.argv.includes('--check') ? 'verified' : 'written'} in ${fileURLToPath(destination)}. No remote operation.`);
